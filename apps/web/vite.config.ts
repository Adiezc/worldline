import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";
import tailwindcss from "@tailwindcss/vite";
import { resolve } from "node:path";

// Override with WORLDLINE_SERVER to point the dev client at another backend (e.g. a test server).
const SERVER = process.env.WORLDLINE_SERVER ?? "localhost:3001";

// Relays /ws to the game server when Vite runs under Bun (`bunx --bun vite`). Vite's `ws: true`
// proxy hangs there: Bun's node:http doesn't pass raw bytes through an upgraded socket, so the
// backend's 101 never reaches the browser. Like Vite's own HMR socket, this accepts the
// connection with Bun's built-in `ws` and opens a second WebSocket to the server, forwarding
// messages both ways. The server reads nothing from the upgrade request, so nothing is lost.
interface RelayClient {
  on(event: "message", cb: (data: Buffer, isBinary: boolean) => void): void;
  on(event: "close", cb: () => void): void;
  send(data: unknown): void;
  close(): void;
  terminate(): void;
}

function bunWsRelay(path: string, target: string): Plugin {
  return {
    name: "worldline-bun-ws-relay",
    configureServer(server) {
      const { WebSocketServer } = import.meta.require("ws");
      const wss = new WebSocketServer({ noServer: true });
      server.httpServer?.on("upgrade", (req, socket, head) => {
        if (new URL(req.url ?? "/", "http://dev").pathname !== path) return;
        wss.handleUpgrade(req, socket, head, (client: RelayClient) => {
          const upstream = new WebSocket(`ws://${target}${req.url}`);
          const pending: (string | Uint8Array<ArrayBuffer>)[] = [];
          client.on("message", (data, isBinary) => {
            const msg = isBinary ? new Uint8Array(data) : data.toString();
            if (upstream.readyState === WebSocket.OPEN) upstream.send(msg);
            else pending.push(msg);
          });
          client.on("close", () => upstream.close());
          upstream.onopen = () => {
            for (const msg of pending.splice(0)) upstream.send(msg);
          };
          upstream.onmessage = (e) => client.send(e.data);
          upstream.onclose = () => client.close();
          upstream.onerror = () => {
            server.config.logger.warn(`[ws relay] can't reach ws://${target}${path}`, { timestamp: true });
            client.terminate();
          };
        });
      });
    },
  };
}

const isBun = !!process.versions.bun;

export default defineConfig({
  plugins: [react(), tailwindcss(), isBun && bunWsRelay("/ws", SERVER)],
  // Base map assets generated by tools/mapgen are served from /map/*.
  publicDir: resolve(import.meta.dirname, "../../packages/mapdata/public"),
  server: {
    port: Number(process.env.WEB_PORT ?? 5173),
    // Tunnel links (VS Code port forwarding, Cloudflare quick tunnels, ngrok) are served on
    // their own hostnames; the tunnel terminates TLS, so the page's wss://…/ws reaches the
    // /ws proxy (or the Bun relay above) as a plain WebSocket upgrade.
    allowedHosts: [".devtunnels.ms", ".trycloudflare.com", ".ngrok-free.app", ".ngrok.app"],
    proxy: {
      "/api": { target: `http://${SERVER}`, changeOrigin: true },
      ...(isBun ? {} : { "/ws": { target: `ws://${SERVER}`, ws: true, changeOrigin: true, secure: false } }),
    },
  },
  worker: { format: "es" },
});
